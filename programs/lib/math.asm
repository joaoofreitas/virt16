; math.asm — math library: fixed-point multiply, signed multiply, sin/cos tables
;
; @import "lib/math.asm"
;
; ── Fixed-point format ────────────────────────────────────────────────────────
; Q8: value stored as integer × 128.
;   +128 = +1.0,  0 = 0.0,  -128 (0xFF80) = -1.0
;
; Sin/cos tables live at:
;   SIN_TABLE = 0x2A00   (256 words, one per angle step)
;   COS_TABLE = 0x2B00
; Angle index: 0–255 maps to 0°–359° (step ≈ 1.4°).
;
; ── Register conventions ──────────────────────────────────────────────────────
; .mul   — unsigned 16×16 → 16 (low bits)
;   in:  R0 = A,  R1 = B
;   out: R2 = A*B (mod 65536)
;   clobbers: R3, R4, R5
;
; .smul  — signed 16×16 → 16 (two's complement)
;   in:  R0 = A (signed),  R1 = B (signed)
;   out: R2 = A*B (signed, low 16 bits)
;   clobbers: R3, R4, R5, R6
;
; Macros expand to MOV + CALL + MOV, so a and b must be registers.
; Do NOT pass (R1, R0) as (a, b) — the first MOV overwrites R0 before R1 is read.
;
; @macro MUL      [dest, a, b]   dest = a * b            (unsigned)
; @macro FPMUL8   [dest, a, b]   dest = (a * b) >> 8     (Q8 × Q8 → Q8 unsigned)
; @macro SMUL     [dest, a, b]   dest = a * b            (signed)
; @macro SFPMUL8  [dest, a, b]   dest = (a * b) >> 8     (Q8 × Q8 → Q8 signed)

; ── Macros ────────────────────────────────────────────────────────────────────

@macro MUL [dest, a, b]
    MOV R0, a
    MOV R1, b
    CALL .mul
    MOV dest, R2
@endmacro

@macro FPMUL8 [dest, a, b]
    MOV R0, a
    MOV R1, b
    CALL .mul
    LOAD R3, #8
    SHR dest, R2, R3
@endmacro

@macro SMUL [dest, a, b]
    MOV R0, a
    MOV R1, b
    CALL .smul
    MOV dest, R2
@endmacro

@macro SFPMUL8 [dest, a, b]
    MOV R0, a
    MOV R1, b
    CALL .smul
    LOAD R3, #8
    SHR dest, R2, R3
@endmacro

