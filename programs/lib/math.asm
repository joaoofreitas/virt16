; ── Subroutine: .mul ──────────────────────────────────────────────────────────
; Unsigned 16-bit multiply via shift-and-add.
; R0=A, R1=B → R2=A*B (low 16 bits). Clobbers R3, R4, R5.

.mul:
    LOAD R2, #0
    LOAD R3, #16
    LOAD R5, #1
    JMP .mul_loop

.mul_loop:
    AND R4, R0, R5
    CMP R4, R5
    JNE .mul_next
    ADD R2, R2, R1

.mul_next:
    SHR R0, R0, R5
    SHL R1, R1, R5
    DEC R3
    JZ .mul_done
    JMP .mul_loop

.mul_done:
    RET

; ── Subroutine: .smul ─────────────────────────────────────────────────────────
; Signed 16-bit multiply (two's complement).
; R0=A (signed), R1=B (signed) → R2=A*B (signed, low 16 bits).
; Clobbers R3, R4, R5, R6.
; Algorithm: extract signs, negate negatives to get abs values, multiply, re-apply sign.

.smul:
    LOAD R6, #0
    LOAD R3, #0x8000
    AND R4, R0, R3
    CMP R4, R3
    JNE .smul_b_sign
    NOT R0, R0
    INC R0
    INC R6

.smul_b_sign:
    AND R4, R1, R3
    CMP R4, R3
    JNE .smul_do_mul
    NOT R1, R1
    INC R1
    INC R6

.smul_do_mul:
    CALL .mul
    LOAD R5, #1
    AND R4, R6, R5
    CMP R4, R5
    JNE .smul_done
    NOT R2, R2
    INC R2

.smul_done:
    RET
